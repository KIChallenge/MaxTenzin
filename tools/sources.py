"""Generate documentation/sources.md: every knowledge item with its source label, ref/URL and retrieval date.

Sources are resolved through the SAME loaders the services use (benefits catalog, bundles, prevention, directory,
appointments, situation, forms), so a dangling citation fails here exactly as it fails at service start.
No LLM, no raw data (docs/) needed. Usage: `make sources`.
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "documentation" / "sources.md"


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _src(ref) -> str:
    """One SourceRef -> 'label · ref · Fassung … · abgerufen …' (only the parts that exist)."""
    if ref is None:
        return "—"
    parts = [ref.label]
    if ref.ref and ref.ref not in ref.label:
        parts.append(f"`{ref.ref}`")
    if ref.in_force:
        parts.append(f"in force {ref.in_force}")
    if ref.retrieved:
        parts.append(f"retrieved {ref.retrieved}")
    return " · ".join(parts)


def _unique(refs) -> list:
    seen, out = set(), []
    for r in refs:
        key = (r.kind, r.label, r.ref)
        if key not in seen:
            seen.add(key)
            out.append(r)
    return out


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
    return lines + [""]


def build() -> str:
    sys.path.insert(0, str(ROOT / "services" / "api"))
    os.environ.setdefault("LLM_MODE", "fake")
    from app.services.appointments.service import providers
    from app.services.benefits import bundles, catalog
    from app.services.directory.service import offices
    from app.services.forms.spec import load_specs
    from app.services.prevention.engine import knowledge as prevention_knowledge
    from app.services.prevention.engine import source_ref as prevention_ref
    from app.services.situation import service as situation

    md = ["<!-- generated by `make sources` (tools/sources.py) – do not edit -->", "",
          "# Sources", "",
          ("Every knowledge item the services read, with the source it cites. Generated from the committed `knowledge/` "
          "through the services' own loaders (a dangling citation fails generation). Legal sources show the in-force "
          "date (Fassung) of the paragraph; external web sources show the retrieval date."), ""]

    # ------------------------------------------------------------------ extracted corpora
    manifest = json.loads((ROOT / "knowledge" / "extracted" / "MANIFEST.json").read_text(encoding="utf-8"))
    md += ["## Extracted corpora (`knowledge/extracted/MANIFEST.json`, `make extract`)", ""]
    rows = []
    for name, m in manifest.items():
        srcs = m["sources"]
        src_txt = srcs[0] if len(srcs) == 1 else f"{len(srcs)} files: " + ", ".join(Path(s).name for s in srcs)
        rows.append([f"`{name}`", str(m["rows"]), src_txt, f"`{m['sources_sha256'][:12]}…`", m["extracted_at"],
                     m.get("notes", "")])
    md += _table(["Corpus", "Rows", "Raw source (docs/, not committed)", "sha256", "Extracted", "Notes"], rows)

    # ------------------------------------------------------------------ benefits + offers
    entries = catalog.entries()
    for kind, title in (("benefit", "Benefits (Leistungen)"), ("offer", "Offers (Angebote / Gesundheitsförderung)")):
        items = [e for e in entries.values() if e.spec.kind == kind]
        md += [f"## {title} – `knowledge/benefits.yaml` ({len(items)})", ""]
        rows = []
        for e in items:
            refs = _unique(e.benefit.legal_basis + e.benefit.sources + [s for _, s in e.criteria.values()])
            rows.append([f"`{e.spec.id}`", e.spec.name_de, e.spec.provider, "<br>".join(_src(r) for r in refs)])
        md += _table(["id", "Name", "Provider", "Sources (legal basis, sources, criteria)"], rows)

    # ------------------------------------------------------------------ bundles
    specs = bundles.specs()
    md += [f"## Situation bundles – `knowledge/bundles.yaml` ({len(specs)})", "",
           ("Benefit/offer/prevention/office/form items cite the sources of the referenced item (see the other "
           "tables); only explicit item sources are listed here."), ""]
    rows = []
    for b in specs.values():
        own = _unique(catalog.resolve(it.source) for it in b.items if it.source is not None)
        refs = ", ".join(f"{it.kind}:{it.ref}" for it in b.items)
        rows.append([f"`{b.id}`", b.title_de, refs, "<br>".join(_src(r) for r in own) or "—"])
    md += _table(["id", "Title", "Items (kind:ref)", "Item sources"], rows)

    # ------------------------------------------------------------------ prevention
    pk = prevention_knowledge()
    raw_sources = pk["sources"]

    def prev(key: str) -> str:
        ref = prevention_ref(key)
        if raw_sources[key].get("retrieved"):
            ref = ref.model_copy(update={"retrieved": raw_sources[key]["retrieved"]})
        return _src(ref)

    md += [(f"## Prevention rules – `knowledge/prevention.yaml` ({len(pk['rules'])} rules, "
           f"{len(pk['family_history']['rules'])} family-history rules)"), ""]
    rows = [[f"`{r['id']}`", r.get("title_de", ""), "<br>".join(dict.fromkeys(prev(k) for k in r.get("sources", [])))]
            for r in pk["rules"]]
    rows += [[f"`family_history.{r['id']}`", r.get("label_de", ""), "<br>".join(dict.fromkeys(prev(k) for k in r.get("sources", [])))]
             for r in pk["family_history"]["rules"]]
    md += _table(["id", "Title", "Sources"], rows)

    # ------------------------------------------------------------------ offices + providers
    offs = offices()
    md += [f"## Offices – `knowledge/offices.yaml` ({len(offs)})", ""]
    md += _table(["id", "Name", "Address", "Source"],
                 [[f"`{o.id}`", o.name, f"{o.address}, {o.zip} {o.city}".strip(", "), _src(o.source)] for o in offs])

    provs = providers()
    real = [p for p in provs if not p.demo]
    md += [(f"## Appointment providers – `knowledge/providers.yaml` ({len(provs)}: {len(real)} real, "
           f"{len(provs) - len(real)} synthetic demo practices)"), "",
           ("Real facilities cite where name/address/phone come from. Demo practices are fictional (name ends in "
           "„(Demo)“) and have no source. All slots are synthetic demo slots."), ""]
    md += _table(["id", "Name", "Real/Demo", "Source"],
                 [[f"`{p.id}`", p.name, "demo" if p.demo else "real", _src(p.source)] for p in provs])

    # ------------------------------------------------------------------ forms
    form_specs = load_specs()
    templates = sorted(p.stem for p in (ROOT / "knowledge" / "forms" / "templates").glob("*.pdf"))
    md += [f"## Form templates – `knowledge/forms/` ({len(form_specs)} mapped of {len(templates)} official templates)",
           ""]
    rows = []
    for t in templates:
        s = form_specs.get(t)
        rows.append([f"`{t}`", s.title_de if s else "—", s.form_version if s else "—",
                     f"`knowledge/forms/templates/{t}.pdf`", "yes" if s else "no (info only)"])
    md += _table(["form_id", "Title", "Version (printed on the form)", "Official template", "Mapped"], rows)

    # ------------------------------------------------------------------ situation
    cfg = situation.cfg()
    md += [f"## Lebenslage rules – `knowledge/situation.yaml` ({len(cfg['rules'])} rules)", ""]
    rows = []
    for rid, rule in cfg["rules"].items():
        key = rule.get("source")
        src = _src(situation._source(key)) if key else "episode source / follow-up quote of the document"
        rows.append([f"`{rid}`", ", ".join(rule.get("applies_to", [])), src])
    md += _table(["Rule", "Applies to episode types", "Source"], rows)

    return "\n".join(md).rstrip() + "\n"


def main() -> None:
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
